function escapeHtml(str) {
  return str.replace(/&/g, '&amp;').replace(/</g, '&lt;')
    .replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

/**
 * Generates a Liquid snippet for rendering custom field inputs on PDP.
 * Values submitted as line_item.properties via cart form.
 */
export function generateLiquidSnippet(fields) {
  if (!fields?.length) return '';

  const fieldInputs = fields.map(field => {
    const safeLabel = escapeHtml(field.label);
    const name = `properties[${safeLabel}]`;
    const requiredAttr = field.required ? ' required' : '';
    const requiredLabel = field.required ? ' <span class="custom-field-required">*</span>' : '';

    if (field.inputType === 'textarea') {
      return `  <div class="custom-field">
    <label for="custom-field-${field.key}">${safeLabel}${requiredLabel}</label>
    <textarea id="custom-field-${field.key}" name="${name}"${requiredAttr} rows="3"></textarea>
  </div>`;
    }

    const type = field.inputType === 'number' ? 'number' : 'text';
    return `  <div class="custom-field">
    <label for="custom-field-${field.key}">${safeLabel}${requiredLabel}</label>
    <input type="${type}" id="custom-field-${field.key}" name="${name}"${requiredAttr} />
  </div>`;
  });

  return `{% comment %}
  Custom Fields — auto-generated by ToolShopify.
  Do not edit manually. Changes will be overwritten on next deploy.
{% endcomment %}
<div class="custom-fields-container">
${fieldInputs.join('\n')}
</div>

<style>
  .custom-fields-container { margin: 16px 0; }
  .custom-field { margin-bottom: 12px; }
  .custom-field label { display: block; margin-bottom: 4px; font-weight: 500; }
  .custom-field input,
  .custom-field textarea { width: 100%; padding: 8px; border: 1px solid #ccc; border-radius: 4px; font-size: 14px; }
  .custom-field-required { color: #e51c23; }
</style>`;
}
